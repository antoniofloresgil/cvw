#!/bin/bash

set -e

board="$1"
case "$board" in
    ArtyA7)
        constraints="../constraints/opensource-ArtyA7.xdc"
        part="xc7a100tcsg324-1"
        chipdb="${NEXTPNR_XILINX_CHIPDB_XC7A100T:-${NEXTPNR_XILINX_CHIPDB:?NEXTPNR_XILINX_CHIPDB_XC7A100T is not set}}"
        ;;
    nexysa7)
        constraints="../constraints/opensource-NexysA7.xdc"
        part="xc7a100tcsg324-1"
        chipdb="${NEXTPNR_XILINX_CHIPDB_XC7A100T:-${NEXTPNR_XILINX_CHIPDB:?NEXTPNR_XILINX_CHIPDB_XC7A100T is not set}}"
        ;;
    nexysvideo)
        constraints="../constraints/opensource-NexysVideo.xdc"
        part="xc7a200tsbg484-1"
        chipdb="${NEXTPNR_XILINX_CHIPDB_XC7A200T:?NEXTPNR_XILINX_CHIPDB_XC7A200T is not set}"
        ;;
    *) echo "Unsupported open-source board: $board" >&2; exit 1 ;;
esac

out="opensource-$board"
source_dir="../src/CopiedFiles_do_not_add_to_repo"
config_dir="$source_dir/config"
xlen="$(sed -n 's/.*XLEN *= *32.d\([0-9]*\);.*/\1/p' "$config_dir/config.vh")"
mkdir -p "$out"
xray_db="${XRAY_DATABASE_DIR:?XRAY_DATABASE_DIR is not set}"
yosys_xilinx="$(yosys-config --datdir)/xilinx"

# The Nexys Video uses the LiteDRAM DDR3 controller generated by LiteX.  It
# provides the DDR3 subsystem (and Wally's clock) and the AHB bridge connects
# Wally's external memory bus to its Wishbone slave.  By default Wally shares
# the DDR controller's 40 MHz clock; WALLY_CLK_FREQ (Hz) gives Wally its own
# clock instead.
if [ "$board" = "nexysvideo" ]; then
    ./gen-litedram.sh --init-cpu "${INIT_CPU:-vexriscv}" --user-data-width "$xlen" ${WALLY_CLK_FREQ:+--user-clk-freq "$WALLY_CLK_FREQ"}
    ddr_dir="opensource-litedram"
    # Merge the DDR3 pin constraints into the board constraints, dropping the
    # clk100/cpu_reset_n entries (the board XDC already constrains those under
    # the SoC's own port names) and the LiteX-generated create_clock.
    merged="$out/constraints.xdc"
    cat "$constraints" > "$merged"
    grep -vE 'clk100|cpu_reset_n|create_clock' "$ddr_dir/litedram_ddr.xdc" >> "$merged"
    constraints="$merged"
fi

source_list="$out/sources.txt"
# fpgaOpenSource.sv includes cvw.sv, whose macros (e.g. CVW_MULTICORE_PARAMS)
# the other sources use, so it goes first and slang reads one compilation unit.
{
    echo "$source_dir/fpgaOpenSource.sv"
    find "$source_dir" -type f -name '*.sv' -print | sort | grep -vE '/(cvw|fpgaOpenSource)\.sv$'
} > "$source_list"

{
    if [ "$board" = "nexysvideo" ]; then
        echo "read_verilog -lib $yosys_xilinx/cells_sim.v"
        echo "read_verilog -lib $yosys_xilinx/cells_xtra.v"
        echo "read_verilog $ddr_dir/*.v"
    fi
    echo "read_slang --std 1800-2017 --single-unit --ignore-timing --ignore-assertions -I $config_dir -I $source_dir -I ../../config/shared -I ../../src --top fpgaOpenSource $(tr '\n' ' ' < "$source_list")"
    echo "hierarchy -top fpgaOpenSource"
    # ABC9's final &verify equivalence check does not finish in hours on the
    # RV64GC design (450k AND gates); mapping itself takes about two minutes.
    echo "scratchpad -set abc9.verify 0"
    echo "synth_xilinx -flatten -arch xc7 -abc9"
    echo "script $WALLY/fpga/generator/prepare-nextpnr.ys"
    echo "write_json $out/$board.json"
} > "$out/synth.ys"

yosys -l "$out/synthesis.log" "$out/synth.ys"
# Make every CARRY4 legal for nextpnr's atomic carry packer (see the script).
python3 fix-carry4-outputs.py "$out/$board.json" "$out/$board.json"

freq=25
[ "$board" = "nexysvideo" ] && freq=40
# The RV64GC netlist does not route with nextpnr's default seed (router2 stalls
# at about 30 overused wires); seed 2 converges. NEXTPNR_SEED overrides it.
seed="${NEXTPNR_SEED:-}"
[ -z "$seed" ] && [ "$board" = "nexysvideo" ] && [ "$xlen" = 64 ] && seed=2
nextpnr-xilinx \
    --chipdb "$chipdb" \
    --xdc "$constraints" \
    --json "$out/$board.json" \
    --freq "$freq" \
    --write "$out/$board-routed.json" \
    --report "$out/$board-report.json" \
    --fasm "$out/$board.fasm" \
    ${seed:+--seed "$seed"}

PYTHONPATH="$RISCV/prjxray" fasm2frames \
    --db-root "$xray_db" \
    --part "$part" \
    "$out/$board.fasm" \
    "$out/$board.frames"
xc7frames2bit \
    --part_file "$xray_db/$part/part.yaml" \
    --part_name "$part" \
    --frm_file "$out/$board.frames" \
    --output_file "$out/$board.bit"

echo "Generated $out/$board.bit"
