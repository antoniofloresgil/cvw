"""Generate the OpenSBI event map for Wally's fixed-function HPM counters."""

import argparse
from pathlib import Path

# SBI event index, Wally counter, description. Raw events use counter number.
EVENTS = [
    (0x00001, 0, "cycles"),
    (0x00002, 2, "instructions"),
    (0x00003, 13, "cache-references: L1D reads and writes"),
    (0x00004, 14, "cache-misses: L1D reads and writes"),
    (0x00005, 25, "branches: conditional branches, jumps and returns"),
    (0x00006, 26, "branch-misses: mispredicted retired control transfers"),
    (0x10008, 16, "L1-icache-loads"),
    (0x10009, 17, "L1-icache-load-misses"),
]


def generate(counters=32):
    if not 3 <= counters <= 32:
        raise ValueError("COUNTERS must be in 3..32")
    events = [(event, counter, label) for event, counter, label in EVENTS if counter < counters]
    selectors = [f"        <0x{event:05x} 0 1> /* {label} */" for event, counter, label in events if counter >= 3]
    mappings = [f"        <0x{event:05x} 0x{event:05x} 0x{1 << counter:08x}> /* {label} */" for event, counter, label in events]
    raw = [f"        <0 0x{counter:x} 0xffffffff 0xffffffff 0x{1 << counter:08x}>" for counter in range(3, min(counters, 27))]
    lines = ["// SPDX-License-Identifier: Apache-2.0 WITH SHL-2.1", "// Generated by linux/pmu/events.py. Fixed-function event selectors: 0=off, nonzero=on.", "// Requires the matching Wally RTL event table and COUNTERS configuration.", "pmu {", '    compatible = "riscv,pmu";', "    riscv,event-to-mhpmcounters =\n" + ",\n".join(mappings) + ";"]
    if selectors:
        lines.append("    riscv,event-to-mhpmevent =\n" + ",\n".join(selectors) + ";")
    if raw:
        lines.append("    riscv,raw-event-to-mhpmcounters =\n" + ",\n".join(raw) + ";")
    return "\n".join([*lines, "};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--counters", type=int, default=32)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(generate(args.counters))


if __name__ == "__main__":
    main()
